/**
 * Regenerates `src/components/IconMap.tsx` from TechStack icon components.
 *
 * Each file in `src/components/TechStack/` must export:
 *   export const iconKey = "Display Name";
 * and a default SVG component.
 *
 * Run via `pnpm generate-icons` after adding or renaming a tech icon.
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const techStackDir = path.join(root, "src/components/TechStack");
const outPath = path.join(root, "src/components/IconMap.tsx");

type IconEntry = {
	file: string;
	importName: string;
	iconKey: string;
};

const ICON_KEY_RE = /export\s+const\s+iconKey\s*=\s*(["'])([^"']+)\1\s*;/;
const DEFAULT_EXPORT_RE = /export\s+default\s+(\w+)\s*;/;

function quoteKey(key: string): string {
	return /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key);
}

function mapEntry({ importName, iconKey }: IconEntry): string {
	if (importName === iconKey) {
		return `\t${importName},`;
	}
	return `\t${quoteKey(iconKey)}: ${importName},`;
}

async function collectIcons(): Promise<IconEntry[]> {
	const files = (await readdir(techStackDir))
		.filter((name) => name.endsWith(".tsx"))
		.sort((a, b) => a.localeCompare(b));

	const entries: IconEntry[] = [];
	const seenKeys = new Map<string, string>();

	for (const file of files) {
		const source = await readFile(path.join(techStackDir, file), "utf8");
		const keyMatch = source.match(ICON_KEY_RE);
		const defaultMatch = source.match(DEFAULT_EXPORT_RE);

		if (!keyMatch) {
			throw new Error(
				`${file}: missing \`export const iconKey = "..."\`. Add a canonical CV/UI key.`,
			);
		}
		if (!defaultMatch) {
			throw new Error(
				`${file}: missing \`export default ComponentName\`.`,
			);
		}

		const iconKey = keyMatch[2];
		const importName = defaultMatch[1];
		const previous = seenKeys.get(iconKey);
		if (previous) {
			throw new Error(
				`Duplicate iconKey ${JSON.stringify(iconKey)} in ${previous} and ${file}`,
			);
		}
		seenKeys.set(iconKey, file);

		entries.push({ file, importName, iconKey });
	}

	entries.sort((a, b) => a.iconKey.localeCompare(b.iconKey));
	return entries;
}

function renderIconMap(entries: IconEntry[]): string {
	// ASCII path order so Biome organize-imports stays clean (Mysql before mongo).
	const imports = [...entries]
		.sort((a, b) => (a.file < b.file ? -1 : a.file > b.file ? 1 : 0))
		.map(
			({ file, importName }) =>
				`import ${importName} from "./TechStack/${file.replace(/\.tsx$/, "")}";`,
		)
		.join("\n");

	const mapBody = entries.map(mapEntry).join("\n");

	return `/* AUTO-GENERATED by scripts/generate-icon-map.ts — do not edit by hand.
 * Add a component under TechStack/ with \`export const iconKey = "..."\` then run:
 *   pnpm generate-icons
 */
import { forwardRef } from "react";
${imports}

export const iconMap = {
${mapBody}
};

/** Canonical skill / tech keys shared by CV JSON and UI icon rendering. */
export type IconMapKey = keyof typeof iconMap;

export const iconKeys = Object.keys(iconMap) as [IconMapKey, ...IconMapKey[]];

type TechIconsProps = {
	iconName: IconMapKey;
};

const TechIcons = forwardRef<SVGSVGElement, TechIconsProps>(
	({ iconName, ...props }, ref) => {
		const Icon = iconMap[iconName];

		if (!Icon) {
			console.warn(\`Icon "\${iconName}" not found in iconMap.\`);
			return null;
		}

		return (
			<Icon ref={ref} {...props} className="aspect-square h-5 w-auto p-0.5" />
		);
	},
);

TechIcons.displayName = "TechIcons";

export default TechIcons;
`;
}

async function main() {
	const entries = await collectIcons();
	const contents = renderIconMap(entries);
	await writeFile(outPath, contents);
	console.log(
		`Wrote ${path.relative(root, outPath)} (${entries.length} icons)`,
	);
	for (const { iconKey, file } of entries) {
		console.log(`  - ${iconKey} ← ${file}`);
	}
}

main().catch((error) => {
	console.error(error);
	process.exit(1);
});
